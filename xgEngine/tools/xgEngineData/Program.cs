using System.Reflection;
using System.Runtime.InteropServices;
using System.Text.Json;
using xg;
using xg.editor;

namespace xgEngineData;

// Builds gameroot/engine/assets into gameroot/engine/data.
//   xgEngineData [--gameroot <dir>]              build every asset (fails on an asset without a meta)
//   xgEngineData [--gameroot <dir>] --new <path>  write a meta with a new GUID for a new asset (path relative to assets)
// Engine GUIDs are referenced by projects, so the build never creates or replaces a meta by itself.
internal static class Program
{
    private static string _bin = string.Empty;

    private static int Main(string[] args)
    {
        string? gameroot = null;
        List<string> newAssets = new();
        for (int i = 0; i < args.Length; i++)
        {
            if (args[i] == "--gameroot" && i + 1 < args.Length)
                gameroot = args[++i];
            else if (args[i] == "--new" && i + 1 < args.Length)
                newAssets.Add(args[++i]);
            else
            {
                Console.Error.WriteLine($"xgEngineData: unknown argument '{args[i]}'");
                return 2;
            }
        }
        gameroot ??= FindGameRoot();
        if (gameroot is null)
        {
            Console.Error.WriteLine("xgEngineData: gameroot not found; pass --gameroot");
            return 2;
        }
        gameroot = Path.GetFullPath(gameroot);
        _bin = Path.Combine(gameroot, "bin");
        NativeLibrary.SetDllImportResolver(typeof(ImageFile).Assembly, ResolveNative);
        NativeLibrary.SetDllImportResolver(typeof(Program).Assembly, ResolveNative);

        string assets = Path.Combine(gameroot, "engine", "assets");
        string data = Path.Combine(gameroot, "engine", "data");
        AssetPipeline pipeline = new(data) { LowerCaseFolders = true };
        TextureAssets.Register(pipeline, DecodeImage);
        MeshAssets.Register(pipeline);
        PrimitiveAssets.Register(pipeline);
        ShaderAssets.Register(pipeline, new DxcShaderCompiler(Path.Combine(gameroot, "sdk")));
        MaterialAssets.Register(pipeline);
        ArchetypeAssets.Register(pipeline);

        if (newAssets.Count > 0)
            return CreateMetas(pipeline, assets, newAssets);
        return Build(pipeline, assets);
    }

    private static int CreateMetas(AssetPipeline pipeline, string assets, List<string> paths)
    {
        int failed = 0;
        foreach (string relative in paths)
        {
            string full = Path.GetFullPath(Path.Combine(assets, relative));
            if (!File.Exists(full) || !pipeline.CanImport(full))
            {
                Console.Error.WriteLine($"xgEngineData: {relative} is not an importable file");
                failed++;
                continue;
            }
            if (AssetMetaStore.TryRead(full, out AssetMeta? existing) && existing is not null && AssetMeta.IsValidGuid(existing.Guid))
            {
                Console.Error.WriteLine($"xgEngineData: {relative} already has the GUID {existing.Guid}");
                failed++;
                continue;
            }
            AssetMeta meta = AssetMeta.Create();
            pipeline.WriteDefaultSettings(full, meta);
            AssetMetaStore.Write(full, meta);
            Console.WriteLine($"xgEngineData: {relative} -> {meta.Guid}");
        }
        return failed == 0 ? 0 : 1;
    }

    private static int Build(AssetPipeline pipeline, string assets)
    {
        if (!Directory.Exists(assets))
        {
            Console.Error.WriteLine($"xgEngineData: {assets} doesn't exist");
            return 1;
        }
        List<string> sources = Directory.EnumerateFiles(assets, "*", SearchOption.AllDirectories)
            .Where(pipeline.CanImport).Order(StringComparer.OrdinalIgnoreCase).ToList();
        Dictionary<string, string> owners = new(StringComparer.OrdinalIgnoreCase);
        int failed = 0, built = 0;
        foreach (string source in sources)
        {
            string relative = Path.GetRelativePath(assets, source).Replace('\\', '/');
            if (!AssetMetaStore.TryRead(source, out AssetMeta? meta) || meta is null || !AssetMeta.IsValidGuid(meta.Guid))
            {
                Console.Error.WriteLine($"error: engine asset {relative} has no meta. Engine GUIDs are never generated by the build; run xgEngineData --new {relative} once and commit the meta.");
                failed++;
                continue;
            }
            if (owners.TryGetValue(meta.Guid, out string? other))
            {
                Console.Error.WriteLine($"error: engine assets {other} and {relative} share the GUID {meta.Guid}");
                failed++;
                continue;
            }
            owners[meta.Guid] = relative;
            AssetBuildRequest request = new(meta.Guid, source, null, meta.ImportSettings, meta.ProcessSettings, meta.Items,
                imported => UpdateItems(source, relative, imported));
            AssetBuildResult result = pipeline.Build(request);
            switch (result.Status)
            {
                case AssetBuildStatus.Failed:
                case AssetBuildStatus.PreviouslyFailed:
                    Console.Error.WriteLine($"error: {relative}: {result.Error}");
                    failed++;
                    break;
                case AssetBuildStatus.Imported:
                case AssetBuildStatus.Processed:
                    built++;
                    Console.WriteLine($"xgEngineData: built {relative}");
                    break;
            }
        }
        int removed = pipeline.RemoveOrphans(new HashSet<string>(owners.Keys, StringComparer.OrdinalIgnoreCase));
        Console.WriteLine($"xgEngineData: {sources.Count} engine asset(s), {built} built, {failed} failed, {removed} removed");
        return failed == 0 ? 0 : 1;
    }

    private static AssetItemUpdate? UpdateItems(string source, string relative, IEnumerable<ImportedAssetItem> imported)
    {
        try
        {
            AssetMeta meta = AssetMetaStore.Read(source);
            AssetItemUpdate update = AssetItemTable.Update(meta.Items, imported);
            foreach (string warning in update.Warnings)
                Console.WriteLine($"warning: {relative}: {warning}");
            meta.Items = update.Items;
            AssetMetaStore.Write(source, meta);
            return update;
        }
        catch (Exception e) when (e is IOException or JsonException or UnauthorizedAccessException)
        {
            Console.Error.WriteLine($"error: could not update the items of {relative}: {e.Message}");
            return null;
        }
    }

    private static DecodedImage? DecodeImage(string path)
    {
        byte[]? pixels = ImageFile.LoadRGBA(path, out int width, out int height);
        return pixels is null ? null : new DecodedImage(width, height, pixels);
    }

    private static string? FindGameRoot()
    {
        for (DirectoryInfo? d = new(AppContext.BaseDirectory); d != null; d = d.Parent)
        {
            string candidate = Path.Combine(d.FullName, "gameroot");
            if (Directory.Exists(Path.Combine(candidate, "engine")))
                return candidate;
        }
        return null;
    }

    private static IntPtr ResolveNative(string name, Assembly assembly, DllImportSearchPath? searchPath)
    {
        if (name != "xgScriptNative" && name != "xgEditorKernel")
            return IntPtr.Zero;
        string file = OperatingSystem.IsWindows() ? name + ".dll" : name + (OperatingSystem.IsMacOS() ? ".dylib" : ".so");
        string path = Path.Combine(_bin, file);
        return File.Exists(path) ? NativeLibrary.Load(path) : IntPtr.Zero;
    }
}
