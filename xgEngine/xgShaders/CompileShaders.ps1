# Compiles every xgShaders/src/<category>.<feature>.hlsl (entry points VSMain and PSMain) with DXC into
#   compiled/dxil.<category>.<feature>.h   (xg::shaders::dxil,  uint8_t arrays, D3D12)
#   compiled/spv.<category>.<feature>.h    (xg::shaders::spirv, uint32_t arrays, Vulkan 1.3)
# DXC needs SPIR-V codegen: the GitHub release or the Vulkan SDK's dxc (not the Windows SDK one).
# Lookup: -Dxc, $env:XG_DXC, xgEngine\3rdparty\dxc\bin\x64\dxc.exe (vendored), $env:VULKAN_SDK\Bin\dxc.exe.
# Without DXC the checked-in headers are kept and the script exits successfully.
param(
    [string]$Dxc = ""
)
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$srcDir = Join-Path $root "src"
$outDir = Join-Path $root "compiled"
$tmpDir = Join-Path $root "obj"

$candidates = @($Dxc, $env:XG_DXC, (Join-Path $root "..\3rdparty\dxc\bin\x64\dxc.exe"))
if ($env:VULKAN_SDK) { $candidates += (Join-Path $env:VULKAN_SDK "Bin\dxc.exe") }
$dxcPath = $candidates | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
if (-not $dxcPath) {
    Write-Host "xgShaders: DXC not found (set XG_DXC); using the checked-in xgShaders/compiled headers."
    exit 0
}

New-Item -ItemType Directory -Force $outDir, $tmpDir | Out-Null

$stages = @(
    @{ Entry = "VSMain"; Profile = "vs_6_0"; Suffix = "VS" },
    @{ Entry = "PSMain"; Profile = "ps_6_0"; Suffix = "PS" }
)
$targets = @(
    @{ Ext = "dxil"; Namespace = "dxil";  Args = @("-O3", "-Wno-ignored-attributes");                    Word = 1 },
    @{ Ext = "spv";  Namespace = "spirv"; Args = @("-O3", "-spirv", "-fspv-target-env=vulkan1.3");        Word = 4 }
)

function Format-Array([byte[]]$bytes, [int]$word) {
    $items = New-Object System.Collections.Generic.List[string]
    if ($word -eq 4) {
        for ($i = 0; $i -lt $bytes.Length; $i += 4) { $items.Add(("0x{0:x8}" -f [BitConverter]::ToUInt32($bytes, $i))) }
        $perLine = 8
    } else {
        foreach ($b in $bytes) { $items.Add(("0x{0:x2}" -f $b)) }
        $perLine = 16
    }
    $lines = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $items.Count; $i += $perLine) {
        $count = [Math]::Min($perLine, $items.Count - $i)
        $lines.Add("        " + (($items.GetRange($i, $count)) -join ", ") + ",")
    }
    return $lines -join "`r`n"
}

$failed = $false
foreach ($file in Get-ChildItem $srcDir -Filter *.hlsl) {
    $name = $file.BaseName
    $parts = $name.ToLowerInvariant().Split('.')
    $varBase = $parts[0] + (($parts | Select-Object -Skip 1 | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join '')
    foreach ($target in $targets) {
        $arrays = @()
        foreach ($stage in $stages) {
            $bin = Join-Path $tmpDir "$($target.Ext).$name.$($stage.Suffix)"
            $dxcArgs = @("-nologo", "-T", $stage.Profile, "-E", $stage.Entry) + $target.Args + @("-Fo", $bin, $file.FullName)
            & $dxcPath @dxcArgs
            if ($LASTEXITCODE -ne 0) { $failed = $true; continue }
            $bytes = [IO.File]::ReadAllBytes($bin)
            $type = if ($target.Word -eq 4) { "uint32_t" } else { "uint8_t" }
            $arrays += "    alignas(4) inline constexpr $type _$varBase$($stage.Suffix)[] =`r`n    {`r`n$(Format-Array $bytes $target.Word)`r`n    };"
        }
        if ($failed) { continue }
        $header = @(
            "// Copyright (c) 2026 John David Uy",
            "// Licensed under the MIT License. See LICENSE for details.",
            "//",
            "// Generated by xgShaders/CompileShaders.ps1 from src/$($file.Name). Do not edit.",
            "#pragma once",
            "#include <cstdint>",
            "",
            "namespace xg::shaders::$($target.Namespace) {",
            "",
            ($arrays -join "`r`n`r`n"),
            "",
            "}",
            ""
        ) -join "`r`n"
        $outFile = Join-Path $outDir "$($target.Ext).$name.h"
        [IO.File]::WriteAllText($outFile, $header, (New-Object Text.UTF8Encoding $false))
        Write-Host "xgShaders: $($file.Name) -> compiled\$($target.Ext).$name.h"
    }
}
if ($failed) { exit 1 }
exit 0
