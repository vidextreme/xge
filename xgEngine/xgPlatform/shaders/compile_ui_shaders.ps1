# Compiles UIShader.hlsl for SDL GPU (DXBC + DXIL) and writes UIShaderBlobs.h.
$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$kit = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin" -Directory | Where-Object { Test-Path "$($_.FullName)\x64\dxc.exe" } | Sort-Object Name | Select-Object -Last 1
$dxc = "$($kit.FullName)\x64\dxc.exe"
$fxc = "$($kit.FullName)\x64\fxc.exe"
$src = Join-Path $here "UIShader.hlsl"
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) "xgUIShaders"
New-Item -ItemType Directory -Force $tmp | Out-Null

& $fxc /nologo /T vs_5_1 /E VSMain /O3 /Fo "$tmp\vs.dxbc" $src | Out-Null
& $fxc /nologo /T ps_5_1 /E PSMain /O3 /Fo "$tmp\ps.dxbc" $src | Out-Null
& $dxc -T vs_6_0 -E VSMain -O3 -Fo "$tmp\vs.dxil" $src | Out-Null
& $dxc -T ps_6_0 -E PSMain -O3 -Fo "$tmp\ps.dxil" $src | Out-Null

$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("// Copyright (c) 2026 John David Uy`r`n// Licensed under the MIT License. See LICENSE for details.`r`n")
[void]$sb.Append("// Generated by compile_ui_shaders.ps1 from UIShader.hlsl. Do not edit.`r`n#pragma once`r`n#include <cstdint>`r`n`r`n")
foreach ($item in @(@("UIVertexDXBC", "vs.dxbc"), @("UIFragmentDXBC", "ps.dxbc"), @("UIVertexDXIL", "vs.dxil"), @("UIFragmentDXIL", "ps.dxil"))) {
    $bytes = [System.IO.File]::ReadAllBytes((Join-Path $tmp $item[1]))
    [void]$sb.Append("static const uint8_t $($item[0])[$($bytes.Length)] = {`r`n")
    for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        $row = ($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { "0x{0:x2}" -f $_ }) -join ","
        [void]$sb.Append("    $row,`r`n")
    }
    [void]$sb.Append("};`r`n`r`n")
}
[System.IO.File]::WriteAllText((Join-Path $here "UIShaderBlobs.h"), $sb.ToString())
Write-Output "UIShaderBlobs.h written"
