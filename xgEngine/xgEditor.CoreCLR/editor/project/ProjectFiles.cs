using System.Text;

namespace xgEditor.CoreCLR
{
    // Creates projects from the SDK template and (re)generates the files the editor owns: <Name>.csproj, <Name>.slnx and
    // Library/Generated/ScriptEntry.g.cs. Files are only rewritten when their content changes. Scripts are globbed by
    // the SDK targets, so adding files under Assets/ never requires regeneration.
    public static class ProjectFiles
    {
        private const string NameToken = "__NAME__";

        // gameroot\sdk\ (with a trailing separator), next to the gameroot\bin folder the editor runs from.
        public static string SdkDirectory
        {
            get
            {
                string bin = Path.GetDirectoryName(typeof(ProjectFiles).Assembly.Location) ?? AppContext.BaseDirectory;
                return Path.GetFullPath(Path.Combine(bin, "..", "sdk")) + Path.DirectorySeparatorChar;
            }
        }

        public static string TemplateDirectory => Path.Combine(SdkDirectory, "templates", "GameProject");

        // Creates a project from the template at root (when it has no manifest yet) and returns it.
        public static ProjectInfo? Create(string root)
        {
            ProjectInfo? existing = ProjectInfo.Load(root);
            if (existing is not null)
                return existing;

            if (!Directory.Exists(TemplateDirectory))
            {
                xg.Debug.LogError($"[Project] Template not found at {TemplateDirectory}. Build XGE.slnx to install the SDK.");
                return null;
            }

            string name = ProjectInfo.ToIdentifier(new DirectoryInfo(root).Name);
            Directory.CreateDirectory(root);
            foreach (string source in Directory.EnumerateFiles(TemplateDirectory, "*", SearchOption.AllDirectories))
            {
                string relative = Path.GetRelativePath(TemplateDirectory, source).Replace(NameToken, name);
                string target = Path.Combine(root, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                if (File.Exists(target))
                    continue;
                byte[] bytes = File.ReadAllBytes(source);
                string text = Encoding.UTF8.GetString(bytes);
                if (text.Contains(NameToken, StringComparison.Ordinal))
                    bytes = Encoding.UTF8.GetBytes(text.Replace(NameToken, name));
                File.WriteAllBytes(target, bytes);
            }
            xg.Debug.LogSuccess($"[Project] Created {name} at {Path.GetFullPath(root)}");
            return ProjectInfo.Load(root);
        }

        public static void Generate(ProjectInfo project)
        {
            Directory.CreateDirectory(project.GeneratedPath);
            int written = 0;
            written += WriteIfChanged(project.CsprojPath, Csproj(project));
            written += WriteIfChanged(project.SlnxPath, Slnx(project));
            written += WriteIfChanged(Path.Combine(project.GeneratedPath, "ScriptEntry.g.cs"), ScriptEntry(project));
            if (written > 0)
                xg.Debug.Log($"[Project] Generated {written} project file(s) for {project.Name}");
        }

        private static int WriteIfChanged(string path, string content)
        {
            string normalized = content.Replace("\r\n", "\n").Replace("\n", "\r\n");
            if (File.Exists(path) && File.ReadAllText(path) == normalized)
                return 0;
            File.WriteAllText(path, normalized, new UTF8Encoding(false));
            return 1;
        }

        private static string Csproj(ProjectInfo project) => $"""
            <Project>
              <!-- Generated by the XGE editor from {project.Name}.xgproject; regenerated when it changes. Scripts: Assets\**\*.cs -->
              <PropertyGroup>
                <XgeProjectName>{project.Name}</XgeProjectName>
                <XgeSdkDir>{SdkDirectory}</XgeSdkDir>
              </PropertyGroup>
              <Import Project="$(XgeSdkDir)xge.Game.props" />
              <Import Project="Sdk.props" Sdk="Microsoft.NET.Sdk" />
              <Import Project="Sdk.targets" Sdk="Microsoft.NET.Sdk" />
              <Import Project="$(XgeSdkDir)xge.Game.targets" />
            </Project>

            """;

        private static string Slnx(ProjectInfo project) => $"""
            <Solution>
              <Project Path="{project.Name}.csproj" />
            </Solution>

            """;

        private static string ScriptEntry(ProjectInfo project) => $$"""
            // <auto-generated> by the XGE editor. Entry points the engine's CoreCLR host calls for this project's scripts.
            using System.Runtime.InteropServices;

            namespace {{project.ScriptAssemblyName}}
            {
                public static class ScriptEntry
                {
                    [UnmanagedCallersOnly]
                    public static int Init(nint enginePtr, uint moduleID) =>
                        xg.GameScriptHost.Init(enginePtr, moduleID, typeof(ScriptEntry).Assembly) ? 1 : 0;

                    [UnmanagedCallersOnly]
                    public static void Update(float dt) => xg.GameScriptHost.Update(dt);

                    [UnmanagedCallersOnly]
                    public static void Shutdown() => xg.GameScriptHost.Shutdown();

                    [UnmanagedCallersOnly]
                    public static void OnMessage(nint typeName, nint payload, int payloadSize)
                    {
                    }
                }
            }

            """;
    }
}
